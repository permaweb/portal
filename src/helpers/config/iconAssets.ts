const bundledSources = new Set(Object.values(localIconAssets));

export function getBundledIcon(source: string): string | undefined {
	if (typeof source !== 'string') return undefined;
	if (Object.prototype.hasOwnProperty.call(localIconAssets, source)) return localIconAssets[source];
	if (bundledSources.has(source)) return source;
	try {
		const url = new URL(source);
		if (
			['http:', 'https:'].includes(url.protocol) &&
			(url.hostname === 'arweave.net' || url.hostname.endsWith('.arweave.net'))
		) {
			const id = url.pathname.slice(1);
			if (Object.prototype.hasOwnProperty.call(localIconAssets, id)) return localIconAssets[id];
		}
	} catch {
		// Custom icons keep their existing source and gateway retry behavior.
	}
	return undefined;
}
